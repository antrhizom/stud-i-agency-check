export const getBkCurriculum = (subjectId) => bkCurricula[subjectId] || null;

// Alle Leistungsziele eines BK-Lehrplans als flache Liste
export const getBkLeistungsziele = (subjectId) => {
  const c = bkCurricula[subjectId];
  if (!c) return [];
  const out = [];
  for (const sem of c.semester) {
    for (const g of sem.gebiete) {
      for (const z of g.ziele) {
        out.push({ ...z, semester: sem.semester, gebiet: g.name, id: `s${sem.semester}-${z.lnr.replace(/\./g, '')}` });
      }
    }
  }
  return out;
};
