// R-Stufe eines Elements (Gesellschaftsinhalt/Sprachmodus/Schlüsselkompetenz) in einem Thema
export const getRStufe = (subjectId, typ, elementId, themaOrder) => {
  const m = zirkularitaet[subjectId]?.[typ]?.[elementId];
  return m ? (m[String(themaOrder)] || null) : null;
};

// Schlüsselkompetenzen, die einem Thema zugewiesen sind (aus der Matrix), mit R-Stufe
export const getSchluesselForThema = (subjectId, themaOrder) => {
  const sk = zirkularitaet[subjectId]?.schluessel || {};
  const out = [];
  for (const [skId, cell] of Object.entries(sk)) {
    const r = cell[String(themaOrder)];
    if (r) out.push({ skId, r });
  }
  return out.sort((a, b) => a.skId.localeCompare(b.skId, undefined, { numeric: true }));
};
